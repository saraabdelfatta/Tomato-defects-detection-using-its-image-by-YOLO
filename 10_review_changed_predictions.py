
"""
FILE: 10_review_changed_predictions.py

PURPOSE:
    Visually inspect test images where the baseline and
    synthetic-data model made different predictions.

INPUT:
    runs/prediction_analysis/changed_predictions.csv

OUTPUT:
    runs/prediction_analysis/changed_predictions_contact_sheet.jpg

IMPORTANT:
    - Does not modify the original test images.
    - Does not train or evaluate models.
    - Used to investigate why the two models disagree.
"""

from pathlib import Path
import csv
import cv2
import math
import numpy as np

# ------------------------------------------------------------
# 1. PATHS
# ------------------------------------------------------------

PROJECT_PATH = Path(__file__).resolve().parent

ANALYSIS_FOLDER = (
    PROJECT_PATH / "runs" / "prediction_analysis"
)

CSV_PATH = ANALYSIS_FOLDER / "changed_predictions.csv"

OUTPUT_PATH = (
    ANALYSIS_FOLDER / "changed_predictions_contact_sheet.jpg"
)

# Contact-sheet layout.
THUMBNAIL_WIDTH = 240
THUMBNAIL_HEIGHT = 200
LABEL_HEIGHT = 100
COLUMNS = 3

# ------------------------------------------------------------
# 2. LOAD CHANGED PREDICTIONS
# ------------------------------------------------------------

def load_records():
    """Read the disagreement CSV generated by script 09."""
    if not CSV_PATH.is_file():
        raise FileNotFoundError(
            f"Cannot find prediction report:\n{CSV_PATH}\n"
            "Run 09_analyze_model_predictions.py first."
        )

    with CSV_PATH.open(
        "r", newline="", encoding="utf-8"
    ) as file:
        records = list(csv.DictReader(file))

    if not records:
        raise RuntimeError(
            "The CSV contains no changed predictions."
        )

    return records


# ------------------------------------------------------------
# 3. PREPARE IMAGE AND LABEL PANELS
# ------------------------------------------------------------

def make_panel(record):
    """Create one labeled thumbnail for a disagreement."""
    image_path = Path(record["image_path"])
    image = cv2.imread(str(image_path))

    if image is None:
        print(f"Warning: unable to read {image_path}")
        return None

    image = cv2.resize(
        image,
        (THUMBNAIL_WIDTH, THUMBNAIL_HEIGHT),
        interpolation=cv2.INTER_AREA,
    )

    # White space below each image contains the prediction details.
    panel = np.full(
        (
            THUMBNAIL_HEIGHT + LABEL_HEIGHT,
            THUMBNAIL_WIDTH,
            3,
        ),
        255,
        dtype=np.uint8,
    )

    panel[:THUMBNAIL_HEIGHT, :] = image

    actual = record["actual_class"]
    baseline = record["baseline_prediction"]
    experiment = record["experiment_prediction"]

    baseline_correct = record["baseline_correct"]
    experiment_correct = record["experiment_correct"]

    lines = [
        f"Actual: {actual}",
        f"Baseline: {baseline} ({'correct' if baseline_correct == 'True' else 'wrong'})",
        f"Experiment: {experiment} ({'correct' if experiment_correct == 'True' else 'wrong'})",
    ]

    y = THUMBNAIL_HEIGHT + 25

    for line in lines:
        cv2.putText(
            panel,
            line,
            (8, y),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.45,
            (20, 20, 20),
            1,
            cv2.LINE_AA,
        )
        y += 28

    return panel


# ------------------------------------------------------------
# 4. BUILD CONTACT SHEET
# ------------------------------------------------------------

def main():
    records = load_records()

    print(f"Disagreement records found: {len(records)}")

    panels = []

    for record in records:
        panel = make_panel(record)

        if panel is not None:
            panels.append(panel)

    if not panels:
        raise RuntimeError(
            "No images could be loaded to create the contact sheet."
        )

    rows = math.ceil(len(panels) / COLUMNS)

    panel_height, panel_width = panels[0].shape[:2]

    sheet = np.full(
        (
            rows * panel_height,
            COLUMNS * panel_width,
            3,
        ),
        235,
        dtype=np.uint8,
    )

    for index, panel in enumerate(panels):
        row = index // COLUMNS
        column = index % COLUMNS

        y = row * panel_height
        x = column * panel_width

        sheet[
            y:y + panel_height,
            x:x + panel_width
        ] = panel

    ANALYSIS_FOLDER.mkdir(parents=True, exist_ok=True)

    if not cv2.imwrite(str(OUTPUT_PATH), sheet):
        raise RuntimeError(
            f"Could not save contact sheet to {OUTPUT_PATH}"
        )

    print("\nContact sheet saved:")
    print(OUTPUT_PATH)
    print("\nOpen this image to review the model disagreements.")


if __name__ == "__main__":
    main()
